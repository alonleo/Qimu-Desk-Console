import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import vm from 'node:vm';
import ts from 'typescript';
const require = createRequire(import.meta.url);
const schemaSource = readFileSync(new URL('../../core/schemas.ts', import.meta.url), 'utf8');
const schemas = { exports: {}, require };
vm.createContext(schemas);
vm.runInContext(ts.transpileModule(schemaSource, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } }).outputText, schemas);
const request = schemas.exports.aiChatSchema.parse({ messages: [{ role: 'user', content: '创建文档' }], autoSave: true });
assert.equal('autoSave' in request, false, 'legacy clients cannot enable automatic saving');
const route = readFileSync(new URL('../../app/api/ai/chat/route.ts', import.meta.url), 'utf8');
const fn = route.slice(route.indexOf('async function finalizeContent'), route.indexOf('/** SSE 编码'));
let writes = 0;
const drafts = [{ kind: 'knowledge', payload: { title: 'draft' } }, { kind: 'skill', payload: { name: 'draft-skill' } }];
const context = { extractArtifacts: () => ({ reply: '草稿已生成', drafts }), writeArtifact: () => { writes++; } };
vm.createContext(context);
vm.runInContext(ts.transpileModule(fn + '\nglobalThis.finalize = finalizeContent;', { compilerOptions: { target: ts.ScriptTarget.ES2022 } }).outputText, context);
const result = await context.finalize({ content: 'example', quickCmd: null, usedDocs: [], cfg: { id: 1 }, autoSave: true });
assert.equal(writes, 0); assert.equal(result.drafts.length, 2); assert.equal('saveResults' in result, false);
const filtered = await context.finalize({ content: 'example', quickCmd: { kind: 'knowledge' }, usedDocs: [], cfg: { id: 1 } });
assert.equal(filtered.drafts.length, 1); assert.equal(filtered.drafts[0].kind, 'knowledge');
console.log('PASS: legacy autoSave ignored, generated drafts never written, manual-save drafts and command filtering preserved');
